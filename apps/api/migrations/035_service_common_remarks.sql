-- Global, service-specific common remarks. Published inspection templates remain untouched.
CREATE TABLE IF NOT EXISTS service_common_remarks (
  id uuid PRIMARY KEY,
  system_key text NOT NULL CHECK (system_key IN ('automatic_sprinkler','hose_reel','hydrant','fire_alarm_detector','fm200_fire_suppression','co2_fire_extinguisher')),
  wording text NOT NULL CHECK (length(btrim(wording)) BETWEEN 1 AND 300),
  detail_label text,
  detail_options jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(detail_options) = 'array'),
  create_fingerprint text,
  active boolean NOT NULL DEFAULT true,
  created_by bigint REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS service_common_remarks_active_wording ON service_common_remarks (system_key, lower(wording)) WHERE active;

